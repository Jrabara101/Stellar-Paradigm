"""One-off extractor (Stage 2 of the React port): turns the legacy picker
markup (theme / chip / tile-font / tile-effect cards and the effects toggles)
from `git show <rev>:index.html` into src/data/pickers.ts. Kept for reference."""
import json, re, subprocess, sys
from html.parser import HTMLParser

rev = sys.argv[1] if len(sys.argv) > 1 else 'HEAD'
html = subprocess.run(['git', 'show', f'{rev}:index.html'], capture_output=True, check=True).stdout.decode('utf8')

class Tree(HTMLParser):
    VOID = {'img', 'input', 'br'}
    def __init__(self):
        super().__init__(); self.root = {'k': []}; self.stack = [self.root]
    def handle_starttag(self, tag, attrs):
        a = dict(attrs); node = {'t': tag}
        for key in ('style', 'class', 'id', 'onclick', 'data-src', 'alt', 'type'):
            if a.get(key) is not None: node[key] = a[key]
        self.stack[-1].setdefault('k', []).append(node)
        if tag not in self.VOID: self.stack.append(node)
    def handle_endtag(self, tag):
        if tag not in self.VOID and len(self.stack) > 1: self.stack.pop()
    def handle_data(self, data):
        if data.strip(): self.stack[-1].setdefault('k', []).append({'x': re.sub(r'\s+', ' ', data.strip())})

def block(modal_id):
    i = html.index(f'id="{modal_id}"'); a = html.rindex('<div', 0, i); depth = 0
    for m in re.finditer(r'<div\b|</div>', html[a:]):
        depth += 1 if m.group(0) == '<div' else -1
        if depth == 0: return html[a:a + m.end()]

def parse(fragment):
    t = Tree(); t.feed(fragment); return t.root

def walk(node, fn):
    fn(node)
    for k in node.get('k', []): walk(k, fn)

def to_preview(n):
    """Strip ids/handlers and the static lock icon (rendered from state now)."""
    if 'x' in n: return {'x': n['x']}
    if 'font-lock' in n.get('class', ''): return None
    out = {'t': n['t']}
    if n.get('style'): out['s'] = n['style']
    if n.get('class'): out['c'] = n['class']
    if n['t'] == 'img':
        out['src'] = n['data-src']; out['alt'] = n.get('alt', '')
    kids = [p for p in (to_preview(k) for k in n.get('k', [])) if p]
    if kids: out['k'] = kids
    return out

def cards(fragment, id_prefix):
    res = []
    def visit(n):
        if n.get('t') == 'div' and n.get('id', '').startswith(id_prefix) and 'theme-card' in n.get('class', ''):
            preview = next(k for k in n['k'] if 'theme-preview' in k.get('class', ''))
            name_el = next(k for k in n['k'] if 'theme-name' in k.get('class', ''))
            name = name_el['k'][0]['x'].replace('🔒', '').strip()
            p = to_preview(preview); p.pop('c', None)  # card component adds .theme-preview itself
            res.append({'id': n['id'][len(id_prefix):], 'name': name, 'preview': p})
    walk(parse(fragment), visit)
    return res

themes = cards(block('theme-modal-backdrop'), 'theme-card-')
chip_block = block('chip-modal-backdrop')
chips = cards(chip_block, 'chip-card-')
fonts = cards(chip_block, 'font-card-')
effects = cards(block('tile-effects-modal-backdrop'), 'tile-effect-card-')

toggles = []
def visit_toggle(n):
    if n.get('t') == 'input' and n.get('id', '').startswith('fx-switch-'):
        toggles.append(n['id'][len('fx-switch-'):])
walk(parse(block('effects-modal-backdrop')), visit_toggle)
labels = re.findall(r'<span style="font-weight: 900; font-size: 0.95rem;">(.*?)</span>\s*<span class="toggle-description"[^>]*>(.*?)</span>',
                    block('effects-modal-backdrop'))
labels = [l for l in labels if 'Tile Letter Styling' not in l[0]]
assert len(labels) == len(toggles), (len(labels), len(toggles))
fx = [{'key': k, 'title': t.replace('&amp;', '&'), 'description': d.replace('&amp;', '&')} for k, (t, d) in zip(toggles, labels)]
previews = re.findall(r"previewVictoryEffect\('(\w+)'\)\"[^>]*>(.*?)</button>", block('effects-modal-backdrop'))

ts = lambda v: json.dumps(v, ensure_ascii=False, indent=4)
out = f"""// Generated by tools/extract-pickers.py from the legacy index.html picker markup
// (Stage 2 of the React port). Preview trees keep the original inline styles verbatim.
import type {{ PickerItem, EffectToggle }} from './picker-types';

export const THEMES: PickerItem[] = {ts(themes)};

export const CHIP_MATERIALS: PickerItem[] = {ts(chips)};

export const TILE_FONTS: PickerItem[] = {ts(fonts)};

export const TILE_EFFECTS: PickerItem[] = {ts(effects)};

export const EFFECT_TOGGLES: EffectToggle[] = {ts(fx)};

export const VICTORY_PREVIEWS: {{ type: string; label: string }}[] = {ts([{'type': t, 'label': l} for t, l in previews])};
"""
open('src/data/pickers.ts', 'w', encoding='utf8').write(out)
print(f'themes {len(themes)}, chips {len(chips)}, fonts {len(fonts)}, tile effects {len(effects)}, toggles {len(fx)}, previews {len(previews)}')
